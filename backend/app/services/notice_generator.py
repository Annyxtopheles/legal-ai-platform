from datetime import datetime
from typing import Dict, Any

class NoticeGeneratorService:
    @staticmethod
    def generate_notice(notice_type: str, contract_data: Dict[str, Any], custom_reason: str = "") -> Dict[str, Any]:
        date_str = datetime.now().strftime("%d %B, %Y")
        landlord = contract_data.get("landlord_name", "মালিক পক্ষ")
        tenant = contract_data.get("tenant_name", "ভাড়াটিয়া পক্ষ")
        address = contract_data.get("property_address", "ভাড়াকৃত সম্পত্তি")
        rent = contract_data.get("rent_amount", "নির্ধারিত ভাড়া")

        if notice_type == "vacate_notice":
            title = "বাসা / দোকান ছাড়ার আইনি নোটিশ (Vacate Notice)"
            subject = f"বিষয়: {address} এর ভাড়ার চুক্তি অবসান ও প্রাঙ্গণ খালি করিবার নোটিশ।"
            body = f"""তারিখ: {date_str}

বরাবর,
{tenant}
ঠিকানা: {address}

মহোদয়,
আপনার অবগতির জন্য জানানো যাইতেছে যে, আমাদের পারস্পরিক সম্পাদিত ভাড়ার চুক্তিপত্রের শর্তানুযায়ী এবং প্রচলিত বাড়ি ভাড়া নিয়ন্ত্রণ আইন অনুযায়ী, অত্র নোটিশ জারির মাধ্যমে আপনাকে অবগত করা যাইতেছে যে, আগামী ৩০/৬০ দিনের মধ্যে অর্থাৎ মেয়াদান্তে উল্লেখিত ভাড়াকৃত প্রাঙ্গণ সম্পূর্ণ সুস্থ অবস্থায় সকল বকেয়া বিল ও ইউটিলিটি নিষ্পত্তি করিয়া মালিক পক্ষের অনুকূলে দখল হস্তান্তর করিবেন।

কারণ / বিবরণ: {custom_reason or 'চুক্তির মেয়াদ সমাপ্তি অথবা মালিক পক্ষের ব্যক্তিগত/পারিবারিক প্রয়োজনে প্রাঙ্গণ পুনর্দখল আবশ্যক হইয়াছে।'}

উক্ত সময়ের মধ্যে কোনো আপত্তি থাকিলে অনতিবিলম্বে লিখিতভাবে জানাইতে অনুরোধ করা যাইতেছে। অন্যথায় নির্ধারিত তারিখের পর আইনানুগ ব্যবস্থা গ্রহণ করা হইবে।

ধন্যবাদান্তে,
স্বাক্ষর: .......................................
নাম: {landlord}
মোবাইল: {contract_data.get('landlord_phone', '')}
"""

        elif notice_type == "renewal_notice":
            title = "চুক্তি নবায়ন ও শর্ত প্রস্তাবনা পত্র (Contract Renewal Letter)"
            subject = f"বিষয়: {address} এর ভাড়ার চুক্তির মেয়াদ বৃদ্ধি ও নবায়ন প্রসঙ্গে।"
            body = f"""তারিখ: {date_str}

বরাবর,
{tenant}
ঠিকানা: {address}

মহোদয়,
উভয় পক্ষের বিদ্যমান ভাড়ার চুক্তির মেয়াদ আগামী নির্ধারিত তারিখে সমাপ্ত হইতে চলিয়াছে। যেহেতু আপনি একজন নিয়মিত ভাড়াটিয়া হিসেবে প্রাঙ্গণে বসবাস করিতেছেন, উভয় পক্ষের পারস্পরিক স্বার্থে চুক্তিটি আগামী আরও ১/২ বছরের জন্য নবায়ন করিবার প্রস্তাব পেশ করা হইল।

প্রস্তাবিত নতুন শর্তাবলি: {custom_reason or f'মাসিক ভাড়া বর্তমান ৳ {rent} টাকা বহাল থাকিবে অথবা প্রচলিত নিয়মানুযায়ী সামান্য সমন্বয় সাপেক্ষে নতুন চুক্তিপত্র সম্পাদন করা হইবে।'}

উক্ত নবায়নে আপনি সম্মত থাকিলে আগামী ১৫ কার্যদিবসের মধ্যে নতুন চুক্তিপত্র স্বাক্ষরের নিমিত্তে যোগাযোগ করিতে অনুরোধ করা যাইতেছে।

বিনীত,
স্বাক্ষর: .......................................
নাম: {landlord}
"""

        else: # demand_notice
            title = "বকেয়া ভাড়া ও পাওনা নিষ্পত্তির আইনি তাগিদপত্র (Demand Notice for Dues)"
            subject = f"বিষয়: বকেয়া মাসিক ভাড়া অবিলম্বে পরিশোধের তাগিদপত্র।"
            body = f"""তারিখ: {date_str}

বরাবর,
{tenant}
ঠিকানা: {address}

মহোদয়,
উদ্বেগের সহিত জানানো যাইতেছে যে, আমাদের সম্পাদিত চুক্তির ২ নম্বর ধারা অনুযায়ী প্রতি মাসের ৭ তারিখের মধ্যে ভাড়া পরিশোধ করিবার সুস্পষ্ট বাধ্যবাধকতা থাকা সত্ত্বেও, আপনার নিকট বিগত সময়ের ভাড়া বকেয়া পড়িয়া রহিয়াছে।

বকেয়ার বিবরণ: {custom_reason or f'বকেয়া ভাড়ার পরিমাণ: ৳ {rent} টাকা।'}

অতএব, অত্র নোটিশ প্রাপ্তির আগামী ৭ (সাত) কার্যদিবসের মধ্যে সমুদয় বকেয়া টাকা পরিশোধ করিয়া প্রাপ্তিরসিদ গ্রহণ করিবেন। ব্যর্থতায় চুক্তি লঙ্ঘনের দায়ে উচ্ছেদ ও আইনানুগ ক্ষতিপূরণ মামলা দায়ের করা হইবে।

নোটিশ প্রদানকারী,
স্বাক্ষর: .......................................
নাম: {landlord}
"""

        return {
            "notice_type": notice_type,
            "title": title,
            "subject": subject,
            "body": body,
            "date": date_str
        }

notice_generator = NoticeGeneratorService()
